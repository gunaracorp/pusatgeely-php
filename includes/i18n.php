function t(string $section, string $key, string $lang = null): string
{
    global $T;
    $lang = $lang ?? current_lang();
    $val = $T[$lang][$section][$key] ?? $T['id'][$section][$key] ?? $key;
    return is_string($val) ? $val : $key;
}

function t_arr(string $section, string $key, string $lang = null): array
{
    global $T;
    $lang = $lang ?? current_lang();
    $val = $T[$lang][$section][$key] ?? $T['id'][$section][$key] ?? [];
    return is_array($val) ? $val : [];
}

// Bilingual string helper
function tx(array $value, string $lang = null): string
{
    $lang = $lang ?? current_lang();
    return $value[$lang] ?? $value['id'] ?? '';
}
